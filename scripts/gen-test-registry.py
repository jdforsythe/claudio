#!/usr/bin/env python3
"""Generates Tests/Runner/Registry.swift: one XCTestEntry per `func test...` in the test suites (docs/13 D-32)."""
import os, re, sys
root = os.path.join(os.path.dirname(__file__), '..', 'Tests')
entries = []
for target in sorted(os.listdir(root)):
    tdir = os.path.join(root, target)
    if not target.endswith('Tests') or not os.path.isdir(tdir):
        continue
    for dirpath, _, files in os.walk(tdir):
        for name in sorted(files):
            if not name.endswith('.swift'):
                continue
            src = open(os.path.join(dirpath, name)).read()
            for cls in re.finditer(r'(?:@MainActor\s+)?final class (\w+)\s*:\s*XCTestCase\s*\{', src):
                cname = cls.group(1)
                body_start = cls.end()
                # class body ends at the first line that is exactly "}"
                m = re.search(r'^\}', src[body_start:], re.M)
                body = src[body_start: body_start + (m.start() if m else len(src))]
                for fm in re.finditer(r'func (test\w*)\(\)\s*(async)?\s*(throws)?', body):
                    entries.append((cname, fm.group(1)))
out = ['// Generated by scripts/gen-test-registry.py; do not edit.', 'import XCTest', '']
out.append('let allTests: [XCTestEntry] = [')
for cname, fname in entries:
    out.append(f'    XCTestEntry(suite: "{cname}", name: "{fname}") {{ let t = await {cname}(); try await t.runLifecycle {{ try await t.{fname}() }} }},')
out.append(']')
open(os.path.join(root, 'Runner', 'Registry.swift'), 'w').write('\n'.join(out) + '\n')
print(f'✓ {len(entries)} tests registered')
